#!/usr/bin/env python3
"""
Plot CRC benchmark results from CSV file generated by run_crc_benchmark_sweep.sh
"""

import argparse
import pandas as pd
import matplotlib.pyplot as plt
import os

def plot_results(csv_path: str, output_dir: str = None):
    """
    Plot precision and recall vs confidence from CSV results.
    
    Args:
        csv_path: Path to results CSV file
        output_dir: Directory to save plots (default: same dir as CSV)
    """
    # Read results
    df = pd.read_csv(csv_path)
    
    # Filter out N/A values
    df = df[df['precision'] != 'N/A']
    df['confidence'] = df['confidence'].astype(float)
    df['precision'] = df['precision'].astype(float)
    df['recall'] = df['recall'].astype(float)
    df['f1'] = df['f1'].astype(float)
    
    if len(df) == 0:
        print("Error: No valid data to plot")
        return
    
    # Set output directory
    if output_dir is None:
        output_dir = os.path.dirname(csv_path)
    
    # Create figure with subplots
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    
    # Plot 1: Precision and Recall vs Confidence
    ax1 = axes[0]
    ax1.plot(df['confidence'], df['precision'], 'o-', label='Precision', 
             linewidth=2, markersize=8, color='#2E86AB')
    ax1.plot(df['confidence'], df['recall'], 's-', label='Recall', 
             linewidth=2, markersize=8, color='#A23B72')
    ax1.plot(df['confidence'], df['confidence'], '--', label='Target Recall', 
             linewidth=2, alpha=0.5, color='gray')
    ax1.set_xlabel('Confidence Level (Target Recall)', fontsize=12)
    ax1.set_ylabel('Metric Value', fontsize=12)
    ax1.set_title('CRC Benchmark: Precision & Recall vs Confidence', fontsize=14, fontweight='bold')
    ax1.legend(fontsize=11)
    ax1.grid(True, alpha=0.3)
    ax1.set_ylim([0, 1.05])
    
    # Add value labels on points
    for i, row in df.iterrows():
        ax1.annotate(f"{row['precision']:.3f}", 
                     (row['confidence'], row['precision']),
                     textcoords="offset points", xytext=(0,8), ha='center', fontsize=9)
        ax1.annotate(f"{row['recall']:.3f}", 
                     (row['confidence'], row['recall']),
                     textcoords="offset points", xytext=(0,-12), ha='center', fontsize=9)
    
    # Plot 2: F1 Score vs Confidence
    ax2 = axes[1]
    ax2.plot(df['confidence'], df['f1'], 'D-', label='F1 Score', 
             linewidth=2, markersize=8, color='#F18F01')
    ax2.set_xlabel('Confidence Level (Target Recall)', fontsize=12)
    ax2.set_ylabel('F1 Score', fontsize=12)
    ax2.set_title('CRC Benchmark: F1 Score vs Confidence', fontsize=14, fontweight='bold')
    ax2.legend(fontsize=11)
    ax2.grid(True, alpha=0.3)
    ax2.set_ylim([0, 1.05])
    
    # Add value labels on points
    for i, row in df.iterrows():
        ax2.annotate(f"{row['f1']:.3f}", 
                     (row['confidence'], row['f1']),
                     textcoords="offset points", xytext=(0,8), ha='center', fontsize=9)
    
    plt.tight_layout()
    
    # Save figure
    output_path = os.path.join(output_dir, 'crc_benchmark_results.png')
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Plot saved to: {output_path}")
    
    # Also save as PDF
    output_path_pdf = os.path.join(output_dir, 'crc_benchmark_results.pdf')
    plt.savefig(output_path_pdf, bbox_inches='tight')
    print(f"Plot saved to: {output_path_pdf}")
    
    # Display plot
    plt.show()
    
    # Print summary table
    print("\n" + "="*60)
    print("RESULTS SUMMARY")
    print("="*60)
    print(df.to_string(index=False))
    print("="*60)
    
    # Calculate recall coverage (how close actual recall is to target)
    df['recall_coverage'] = df['recall'] / df['confidence']
    print(f"\nRecall Coverage (actual/target):")
    for i, row in df.iterrows():
        coverage = row['recall_coverage'] * 100
        status = "✓" if coverage >= 95 else "⚠" if coverage >= 90 else "✗"
        print(f"  Confidence {row['confidence']:.1f}: {coverage:.1f}% {status}")
    print()


def main():
    parser = argparse.ArgumentParser(description="Plot CRC benchmark results")
    parser.add_argument("csv_file", help="Path to results CSV file")
    parser.add_argument("--output-dir", help="Directory to save plots (default: same as CSV)")
    args = parser.parse_args()
    
    if not os.path.exists(args.csv_file):
        print(f"Error: File not found: {args.csv_file}")
        return
    
    plot_results(args.csv_file, args.output_dir)


if __name__ == "__main__":
    main()

